# -*- coding: utf-8 -*-
"""utils/gender_resolver.py — محلّل جنس العطر من أقوى إشارة متاحة (بلا اختلاق).

القاعدة الذهبية (توجيه المالك 2026-07-10: الدقّة قبل كل شيء): «للجنسين» تُرجَع
فقط حين يقول المصدر صراحةً إنه للجنسين — **لا** كقيمة احتياطية للمجهول. عند غياب
أيّ إشارة نُعيد "" (مجهول) فتُسقِط طبقةُ العرض سطرَ الجنس بدل تلفيق قيمة (نفس مبدأ
«لا نلفّق ما لا نعرفه» المعتمَد في utils/salla_shamel_export.py).

خلفية العطب (الجلسة 18): عمودا gender/extracted_gender في competitor_products_store
فارغان 100% (374,023 صفاً)، فكانت مولّدات الوصف تستنتج الجنس من اسم المنتج وحده —
والاسم يحمل كلمة جنس في ~19% فقط — ثم تسقط الأغلبيةُ على «للجنسين» المثبّتة، فظهر
«كل العطور للجنسين». الإشارة الحقيقية موجودة أصلاً في عمود ``category`` (تصنيف سلة
من Algolia: «... > عطور رجالية/نسائية/للجنسين») لـ95.6% من صفوف العطور، وهو مُحمَّل
فعلاً في حمولة المفقودات لكن يُتجاهَل. هذه الوحدة تقرؤه.

ترتيب الإشارات (الأقوى أولاً):
  1) سلسلة التصنيف ``category`` — مصدر الحقيقة (وسم Algolia، 95.6% تغطية).
  2) الحقل الصريح ``الجنس``/``gender`` إن حمل قيمة حقيقية.
  3) اسم المنتج — كلمة جنس في ~19% فقط.
دالّتان خالصتان قابلتان للاختبار بلا قاعدة/شبكة.
"""
from __future__ import annotations

from typing import Any

# أنماط نسائي/رجالي/للجنسين — مطابقة لمنطق engines.engine.extract_gender المثبّت
# ميدانياً، مع إضافة الصيغ العربية لتصنيفات سلة («رجالية/نسائية») ووسم «للجنسين».
_FEMALE = (
    "نسائي", "نسائى", "نسائية", "نسائيه", "للنساء", "للمرأة", "امرأة", "نساء",
    "فام", "women", "woman", "femme", "for her", "donna", "lady",
)
_MALE = (
    "رجالي", "رجالى", "رجالية", "رجاليه", "للرجال", "رجال", "pour homme",
    "for men", "for him", " men ", " men", " man ", "homme", "uomo", "هوم",
    " مان ", "mans",
)
_UNISEX = ("للجنسين", "الجنسين", "مشترك", "unisex", "for all")


def _pad(value: Any) -> str:
    """نصّ مبطّن بمسافتين (كي تُطابَق الكلمات المحاطة بمسافات مثل `` men ``)."""
    return f" {str(value or '').strip().lower()} "


def gender_from_text(text: Any) -> str:
    """يستنتج الجنس من نصّ واحد (اسم منتج أو سلسلة تصنيف).

    يعيد ``"رجالي"`` / ``"نسائي"`` / ``"للجنسين"`` عند إشارة صريحة، و``""`` عند
    الغياب أو التعارض. لا يُرجع «للجنسين» إلا إذا نصّ المصدر عليها — لا للمجهول.
    """
    t = _pad(text)
    if not t.strip():
        return ""
    # «للجنسين» وسمٌ صريح — يُفحص أولاً (لا يتعارض مع رجالي/نسائي داخل نفس التصنيف).
    if any(k in t for k in _UNISEX):
        return "للجنسين"
    f = any(k in t for k in _FEMALE)
    m = any(k in t for k in _MALE)
    if f and not m:
        return "نسائي"
    if m and not f:
        return "رجالي"
    # تعارض (اسم يحمل الإشارتين) أو غياب ⇒ مجهول — لا اختلاق.
    return ""


def resolve_gender(
    name: Any = "", category: Any = "", explicit: Any = "",
) -> str:
    """أقوى إشارة جنس متاحة من (التصنيف ← الحقل الصريح ← الاسم).

    يعيد ``"رجالي"`` / ``"نسائي"`` / ``"للجنسين"`` أو ``""`` (مجهول ⇒ لا يُعرَض).
    التصنيف أولاً لأنه وسم مصدر الكشط (Algolia) الأدقّ؛ ثم الحقل الصريح؛ ثم الاسم.
    """
    for source in (category, explicit, name):
        g = gender_from_text(source)
        if g:
            return g
    return ""
