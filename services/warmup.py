"""services/warmup.py — تسخين مسبق عند إقلاع الخادم (خيط خلفي، لا يمسّ منطقاً).

**⚠️ متى ينطلق هذا فعلاً — مقيس لا مفترض (2026-07-25):** ينطلق عند **أول جلسة
متصفّح**، لا عند إقلاع الخادم. Streamlit لا ينفّذ ``app.py`` إطلاقاً قبل اتصال
جلسة؛ خادمٌ صحّته 200 ودقائقُ من عمره لم يُنتج سطر التسخين في سجلّه (فحص حيّ على
منفذ 8503). فالمكسب الحقيقي: تُبنى المذكّرة في خيط جانبي **بينما يقرأ المالك
صفحته الأولى**، فتكون جاهزة حين ينتقل إلى «جديد عند المنافسين». ولو ذهب إليها
مباشرةً في أول جلسة فالقفل يجعله ينتظر بناءً واحداً — **لا أسوأ من قبل، ولا أفضل**.

**المشكلة المقيسة (2026-07-25):** أول فتح لصفحة «🆕 جديد عند المنافسين» بعد كل
إعادة تشغيل للخادم يكلّف ثوانيَ طويلة. التفكيك بالقياس في عملية جديدة:

| الجزء | بارد | ثانيةً |
|---|---:|---:|
| ``build_ownership_matcher()`` | **5,941م.ث** | 979م.ث |
| استعلام الصفوف (``new_products_cached``) | 7م.ث | 3م.ث |
| بناء التغذية (``prepare_competitor_feed``) | 50م.ث | 40م.ث |

فالكلفة كلّها في بناء المُطابِق — لا في قراءة القرص كما رُجِّح سابقاً. و
``st.cache_resource`` لا يُملأ إلا من داخل جلسة متصفّح، فالمالك هو من يدفع
الانتظار دائماً. هذا الخيط يدفعه **قبله** بينما يقرأ الصفحة الأولى.

**قواعد صلبة في هذا الملف:**
  • لا يكتب في أي قاعدة بيانات ولا يمسّ تسعيراً/مطابقةً/إرسالاً — بناء قراءةٍ فقط.
  • أي استثناء يُبتلع ويُسجَّل: فشل التسخين يجب أن يعني «بطء كما كان»، لا صفحة مكسورة.
  • خيط ``daemon`` — لا يؤخّر إغلاق الخادم.
  • معطّل افتراضياً لحماية حاويات الذاكرة المحدودة؛ يُفعّل صراحةً بـ``MAHWOUS_WARMUP=1``.
    التسخين يحسّن زمن صفحة «جديد عند المنافسين» لاحقاً، لكنه ليس مطلوباً لفتح
    لوحة التحكم أو لاستعادة نتائج التحليل، ولذلك لا ينبغي أن يتزامن مع أول رسم.
"""
from __future__ import annotations

import logging
import os
import sys
import threading

_log = logging.getLogger("warmup")

_started = False                       # حارس: مرّة واحدة لكل عملية
_lock = threading.Lock()
_DELAY_SEC = 2.0                       # مهلة تُبقي أولوية أول رسم للصفحة


def _warm() -> None:
    """يبني مُطابِق الملكية في المذكّرة على مستوى العملية. يُبتلع كل خطأ."""
    try:
        from ui.pages.new_at_competitors import catalog_signature
        from services.ownership_service import build_ownership_matcher_cached

        sig = catalog_signature()
        build_ownership_matcher_cached(sig)
        _log.info("اكتمل التسخين المسبق لمُطابِق الملكية (بصمة %s)", sig)
    except Exception as exc:           # noqa: BLE001 — تسخين لا يكسر خادماً
        _log.warning("تعذّر التسخين المسبق (يبقى السلوك كما كان): %s", exc)


def start_background_warmup() -> bool:
    """يُطلق التسخين مرّة واحدة لكل عملية. يعيد True إن أُطلق فعلاً الآن.

    يُستدعى من ``app.py`` على مستوى الوحدة — أي عند **كل** إعادة تشغيل سكربت
    Streamlit — فالحارس ``_started`` هو ما يمنع إطلاق خيط لكل تفاعل. وأول تنفيذ
    للوحدة يقع عند أول جلسة متصفّح لا عند إقلاع الخادم (انظر رأس الملف).
    """
    global _started
    # بناء مطابِق الملكية يحمّل فهرساً كبيراً في الذاكرة. عند أول جلسة كان
    # يتزامن مع استعادة ui_session ورسم لوحة التحكم، ما جعل حاوية 1 GiB تدخل
    # BackOff. نجعله opt-in: العرض الأساسي لا يحتاجه، ومن يريد تسخين صفحة
    # «جديد عند المنافسين» يفعّله صراحةً بعد تخصيص ذاكرة مناسبة.
    if os.environ.get("MAHWOUS_WARMUP", "0").strip() != "1":
        return False
    # لا تسخين تحت pytest: اختبارات AppTest تشغّل app.py عشرات المرات، فخيط
    # يبني المُطابِق من القاعدة الحيّة في كل واحدة = ضجيج وحمل بلا فائدة.
    if "pytest" in sys.modules:
        return False
    with _lock:
        if _started:
            return False
        _started = True
    timer = threading.Timer(_DELAY_SEC, _warm)
    timer.daemon = True                # لا يؤخّر إغلاق الخادم
    timer.start()
    return True
